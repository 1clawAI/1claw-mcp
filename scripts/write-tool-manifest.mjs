// Write tool-manifest.json from the catalog this server actually installs.
//
// The count is quoted by the marketing site, the `.well-known/mcp` document
// 1claw.co serves, and the `serverInfo.instructions` an MCP client reads on
// initialize. Hand-copied into all three, they drifted to 160, 30 and 160
// against a real 161. This is the one place it is derived.
//
//   npm run tools:manifest
import { writeFileSync } from "node:fs";
import { installToolsets, TOOL_CATALOG } from "../dist/toolsets.js";
import { TOOLSET_MODULES } from "../dist/toolsets/index.js";

installToolsets(TOOLSET_MODULES);

const byToolset = {};
for (const [, set] of TOOL_CATALOG) byToolset[set] = (byToolset[set] ?? 0) + 1;

const manifest = {
  $comment:
    "Generated by scripts/write-tool-manifest.mjs — do not edit by hand. " +
    "Guarded by src/__tests__/tool-manifest.test.ts.",
  total: TOOL_CATALOG.size,
  byToolset: Object.fromEntries(Object.entries(byToolset).sort()),
};

writeFileSync(
  new URL("../tool-manifest.json", import.meta.url),
  JSON.stringify(manifest, null, 2) + "\n",
);
console.log(`tool-manifest.json: ${manifest.total} tools`);
